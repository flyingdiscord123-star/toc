"""
action.py

Defines actions proposed by an agent.

Actions are immutable descriptions of intended behaviour.
The simulation engine is responsible for validating and executing
these actions.
"""

from __future__ import annotations

from dataclasses import dataclass,field
from typing import Any


@dataclass(slots=True, frozen=True)
class AgentAction:
    """
    Immutable action generated by an agent.

    Parameters
    ----------
    extraction_amount:
        Amount of resource the agent wishes to extract.

    metadata:
        Future extension point for communication, voting,
        trading, or other behaviours.
    """

    extraction_amount: float

    metadata: dict[str, Any] = field(default_factory=dict)